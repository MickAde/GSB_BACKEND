from rest_framework import serializers
from .models import ConformityStatus, NoteConformityReport, NoteStatus, NoteType, NoteUpload

# Max 20 MB per file
MAX_FILE_SIZE_BYTES = 20 * 1024 * 1024

ALLOWED_MIME_TYPES = {
    'pdf': [
        'application/pdf',
        'application/x-pdf',
        'application/octet-stream',
    ],
    'image': [
        'image/jpeg', 'image/jpg', 'image/png', 'image/webp',
        'image/gif', 'image/tiff', 'image/bmp', 'image/heic', 'image/heif',
        'application/octet-stream',
    ],
    'voice': [
        'audio/mpeg', 'audio/mp3', 'audio/mp4', 'audio/m4a', 'audio/x-m4a',
        'audio/wav', 'audio/x-wav', 'audio/ogg', 'audio/webm',
        'audio/aac', 'audio/x-aac', 'audio/flac', 'audio/x-flac',
        'application/octet-stream',
    ],
    'text': [
        'text/plain',
        'text/plain; charset=utf-8',
        'text/plain;charset=utf-8',
        'application/octet-stream',
    ],
    'doc': [
        'application/msword',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'application/vnd.ms-powerpoint',
        'application/vnd.openxmlformats-officedocument.presentationml.presentation',
        'application/vnd.ms-excel',
        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'application/zip',
        'application/octet-stream',
    ],
}


class NoteUploadRequestSerializer(serializers.Serializer):
    """Validates a single-file upload (multipart/form-data)."""
    file = serializers.FileField()
    note_type = serializers.ChoiceField(choices=NoteType.choices)
    subject  = serializers.CharField(max_length=100, required=False, default='', allow_blank=True)
    topic    = serializers.CharField(max_length=100, required=False, default='', allow_blank=True)
    subtopic = serializers.CharField(max_length=100, required=False, default='', allow_blank=True)

    def validate(self, attrs):
        file_obj  = attrs['file']
        note_type = attrs['note_type']

        if file_obj.size > MAX_FILE_SIZE_BYTES:
            raise serializers.ValidationError(
                {'file': f'File size exceeds the 20 MB limit ({file_obj.size / 1024 / 1024:.1f} MB).'}
            )

        content_type = getattr(file_obj, 'content_type', '')
        allowed = ALLOWED_MIME_TYPES.get(note_type, [])
        if allowed and content_type and content_type not in allowed:
            raise serializers.ValidationError(
                {'file': f'File type "{content_type}" is not allowed for note_type "{note_type}".'}
            )

        return attrs


