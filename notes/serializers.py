            'id',
            'owner_name',
            'file_url',
            'file_name',
            'note_type',
            'file_size_bytes',
            'subject',
            'topic',
            'subtopic',
            # Pipeline output
            'raw_ocr_text',
            'ai_summary_paragraph',
            'ai_bullet_points',
            'ai_key_points',
