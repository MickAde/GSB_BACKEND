class ConfirmOCRSerializer(serializers.Serializer):
    """
    Student-reviewed and corrected OCR text.
    Only after this confirmation does AI summarisation begin.
    """
    confirmed_text = serializers.CharField(
        help_text='Student-corrected OCR text. Triggers AI summarisation pipeline.',
        trim_whitespace=True,
    )

    def validate_confirmed_text(self, value):
        if len(value.strip()) < 10:
            raise serializers.ValidationError(
                'Confirmed text is too short. Please provide more content for the AI to summarise.'
            )
        return value.strip()


